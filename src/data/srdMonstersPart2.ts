export const ALL_SRD_MONSTERS: SrdMonsterRaw[] = [...SRD_MONSTERS_A_TO_L, ...SRD_MONSTERS_M_TO_Z];

function modStr(score: number): string {
  const m = Math.floor((score - 10) / 2);
  return m >= 0 ? `+${m}` : `${m}`;
}

function splitMonsterClauses(text?: string, allowSemicolon = false): { name: string; desc: string }[] {
  if (!text) return [];
  const clauses: string[] = [];
  let current = '';
  let depth = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch === '(' || ch === '[') depth++;
    else if (ch === ')' || ch === ']') depth = Math.max(0, depth - 1);
    const isDelim = ch === '.' || (allowSemicolon && ch === ';');
    if (depth === 0 && isDelim) {
      const trimmed = current.trim();
      if (trimmed) clauses.push(trimmed);
      current = '';
    } else {
      current += ch;
    }
  }
  if (current.trim()) clauses.push(current.trim());

  return clauses.map(c => {
    const m = c.match(/^([^(]+?)(?:\s*\(([\s\S]+)\))?$/);
    const name = (m ? m[1] : c).trim();
    const desc = (m && m[2] ? m[2] : c).trim();
    return { name, desc };
  });
}

export function buildMonsterLibraryEntries(): LibraryEntry[] {
  return ALL_SRD_MONSTERS.map((m) => {
    const statLines = [
      `${m.size} ${m.type}, ${m.alignment}`,
      `Armor Class: ${m.ac}${m.acNote ? ` (${m.acNote})` : ''} | Hit Points: ${m.hp} (${m.hitDice}) | Speed: ${m.speed}`,
      `STR ${m.str} (${modStr(m.str)}) | DEX ${m.dex} (${modStr(m.dex)}) | CON ${m.con} (${modStr(m.con)}) | INT ${m.int} (${modStr(m.int)}) | WIS ${m.wis} (${modStr(m.wis)}) | CHA ${m.cha} (${modStr(m.cha)})`,
      `Challenge: ${m.cr} (${m.xp})`,
      m.resistances ? `Damage Resistances: ${m.resistances}` : '',
      m.immunities ? `Immunities: ${m.immunities}` : '',
      m.senses ? `Senses: ${m.senses}` : '',
      m.languages ? `Languages: ${m.languages}` : '',
      '',
      m.traits ? `Traits:\n${m.traits}\n` : '',
      `Actions:\n${m.actions}`,
      m.legendaryActions ? `\nLegendary Actions:\n${m.legendaryActions}` : '',
    ]
      .filter(Boolean)
      .join('\n');

    const parsedTraits = splitMonsterClauses(m.traits, false);
    const parsedActions = [
      ...splitMonsterClauses(m.actions, false),
      ...splitMonsterClauses(m.legendaryActions, true).map(la => ({
        name: `Legendary: ${la.name}`,
        desc: la.desc,
      })),
    ];

    return {
      id: `srd_monster_${m.name.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
      name: m.name,
      category: 'monsters',
      source: 'SRD 5.2.1',
      summary: `${m.size} ${m.type}, ${m.alignment} • AC ${m.ac} • HP ${m.hp} (${m.hitDice}) • CR ${m.cr}`,
      content: statLines,
      stats: {
        ac: m.ac,
        hp: m.hp,
        cr: m.cr,
        speed: m.speed,
        size: m.size,
        type: m.type,
        alignment: m.alignment,
        abilities: {
          str: m.str,
          dex: m.dex,
          con: m.con,
          int: m.int,
          wis: m.wis,
          cha: m.cha,
        },
        traits: parsedTraits.length > 0 ? parsedTraits : undefined,
        actions: parsedActions,
      },
      tags: ['Monster', m.size, m.type.split('(')[0].trim(), `CR ${m.cr}`],
    };
  });
}

