export const ALL_SRD_SPELLS: SrdSpellRaw[] = [...SRD_SPELLS_A_TO_L, ...SRD_SPELLS_M_TO_Z];

export function buildSpellLibraryEntries(): LibraryEntry[] {
  return ALL_SRD_SPELLS.map((s) => {
    const levelLabel = s.level === 0 ? `${s.school} Cantrip` : `Level ${s.level} ${s.school}`;
    const fullDesc = [
      `${levelLabel} (${s.classes})`,
      `Casting Time: ${s.castingTime} | Range: ${s.range} | Components: ${s.components} | Duration: ${s.duration}`,
      s.damage ? `Damage: ${s.damage}${s.damageType ? ` ${s.damageType}` : ''}` : '',
      s.healing ? `Healing: ${s.healing}` : '',
      s.saveType ? `Save: ${s.saveType}` : '',
      s.attackType ? `Attack: ${s.attackType}` : '',
      s.aoe ? `Area of Effect: ${s.aoe}` : '',
      '',
      s.desc,
    ]
      .filter(Boolean)
      .join('\n');

    const ctLower = s.castingTime.toLowerCase();
    const actionType: 'Action' | 'Bonus Action' | 'Reaction' | 'Special' = ctLower.includes('bonus action')
      ? 'Bonus Action'
      : ctLower.includes('reaction')
      ? 'Reaction'
      : ctLower.includes('action')
      ? 'Action'
      : 'Special';

    return {
      id: `srd_spell_${s.name.toLowerCase().replace(/[^a-z0-9]+/g, '_')}`,
      name: s.name,
      category: 'spells',
      source: 'SRD 5.2.1',
      summary: `${levelLabel} • ${s.castingTime} • ${s.range} — ${s.desc.slice(0, 140)}${s.desc.length > 140 ? '...' : ''}`,
      content: fullDesc,
      stats: {
        level: s.level,
        school: s.school,
        castingTime: s.castingTime,
        range: s.range,
        components: s.components,
        duration: s.duration,
        actionType,
        damage: s.damage,
        damageType: s.damageType,
        healing: s.healing,
        saveType: s.saveType,
        attackType: s.attackType,
        areaOfEffect: s.aoe,
      },
      tags: [
        'Spell',
        s.school,
        s.level === 0 ? 'Cantrip' : `Level ${s.level}`,
        actionType,
        ...(s.castingTime.toLowerCase().includes('ritual') || s.duration.toLowerCase().includes('ritual') ? ['Ritual'] : []),
        ...(s.duration.toLowerCase().includes('concentration') ? ['Concentration'] : []),
        ...s.classes.split(',').map((c) => c.trim()),
        ...(s.damageType ? [`${s.damageType} Damage`, s.damageType] : []),
        ...(s.healing ? ['Healing'] : []),
      ],
    };
  });
}

